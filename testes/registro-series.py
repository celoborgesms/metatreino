#!/usr/bin/env python3
"""Registro de séries (carga × peso do corpo × tempo), 1ª série e descanso, ordem da ficha (créditos no fim),
seleção de texto e a "semana com menos tempo" na tela. Firebase simulado.
Uso: python3 testes/registro-series.py URL"""
import asyncio, sys
from playwright.async_api import async_playwright
URL = sys.argv[1] if len(sys.argv) > 1 else 'http://localhost:8765/index.html'
ok = 0; falhas = []
def confere(nome, cond, info=''):
    global ok
    if cond: ok += 1; print('  ✅', nome)
    else: falhas.append(nome); print('  ❌', nome, info)
async def main():
    async with async_playwright() as p:
        b = await p.chromium.launch(executable_path='/usr/bin/google-chrome', args=['--no-sandbox'])
        pg = await b.new_page(viewport={'width':390,'height':844}); erros = []; pg.on('pageerror', lambda e: erros.append(str(e)))
        await pg.goto(URL); await pg.wait_for_function("document.querySelector('.screen.active').id==='scr-quiz'")
        await pg.evaluate("mtSemente()"); await pg.wait_for_timeout(1200); await pg.evaluate("try{closeAwards()}catch(e){}; closeModal(); goTab('sessions')")
        print('1. Exercício com carga')
        ex = await pg.evaluate("(()=>{ const w = currentSelectedWorkout(state.modules.lift); const e = w.exercises.find(x=>exTipoRegistro(x.id)==='carga'); return {id:e.id, name:e.name, rest:e.rest}; })()")
        await pg.evaluate(f"progressoHoje = (state.progress['{ex['id']}']||[]); state.progress['{ex['id']}'] = (state.progress['{ex['id']}']||[]).filter(p=>new Date(p.date).toDateString()!==new Date().toDateString()); stopRestTimer(); openSetLog('{ex['id']}', {repr(ex['name'])})")
        cols = await pg.evaluate("document.querySelector('#modal-inner .set-row').innerText")
        confere('mostra a coluna de carga', 'CARGA' in cols, cols)
        await pg.evaluate("addSet()")
        confere('1ª série NÃO inicia o descanso', await pg.evaluate("!restTimerInt"))
        await pg.evaluate("updateSet(0,'reps','10'); updateSet(0,'peso','40')")
        confere('editar a série não inicia o descanso', await pg.evaluate("!restTimerInt"))
        await pg.evaluate("addSet()")
        confere('"+ Nova série" depois da 1ª: inicia o descanso', await pg.evaluate("!!restTimerInt"))
        alvo = await pg.evaluate(f"parseRestSeconds({repr(ex['rest'])})")
        confere('descanso = exatamente o do exercício no treino', await pg.evaluate("restTotalSeg") == alvo, (await pg.evaluate("restTotalSeg"), alvo, ex['rest']))
        await pg.evaluate("delSet(1)")
        confere('excluir série não dispara outro descanso nem duplica', await pg.evaluate("document.querySelectorAll('#rest-timer-banner').length") == 1)
        await pg.evaluate("restPausa()"); a = await pg.evaluate("restRestante()"); await pg.wait_for_timeout(1200)
        confere('pausar o descanso', await pg.evaluate("restRestante()") == a)
        await pg.evaluate("restPausa(); restFimEm = Date.now()-10"); await pg.wait_for_timeout(600)
        confere('descanso termina', await pg.evaluate("!restTimerInt"))
        await pg.evaluate("closeSetLog(true)")
        confere('salvar a última série não inicia descanso', await pg.evaluate("!restTimerInt"))
        print('2. Exercício com o peso do corpo')
        await pg.evaluate("closeModal(); state.progress['flexao-de-braco'] = []; delete state.prs['flexao-de-braco']; openSetLog('flexao-de-braco','Flexão de Braço'); addSet(); updateSet(0,'reps','15')")
        cols = await pg.evaluate("document.querySelector('#modal-inner .set-row').innerText")
        confere('sem coluna de carga', 'CARGA' not in cols and 'REPETIÇÕES' in cols, cols)
        confere('oferece carga extra opcional', await pg.evaluate("/carga extra/i.test(document.getElementById('modal-inner').innerText)"))
        await pg.evaluate("closeSetLog(true)")
        pr = await pg.evaluate("state.prs['flexao-de-braco']")
        confere('recorde de repetições sem carga (peso 0 não é falha)', pr and pr.get('reps') == 15, pr)
        await pg.evaluate("stopRestTimer(); closeModal(); openSetLog('flexao-de-braco','Flexão de Braço'); curLog.cargaExtra=true; renderSetLogModal()")
        confere('pedindo carga extra, a coluna aparece', 'CARGA EXTRA' in await pg.evaluate("document.querySelector('#modal-inner .set-row').innerText"))
        await pg.evaluate("closeSetLog(false); stopRestTimer()")
        print('3. Isométrico')
        await pg.evaluate("closeModal(); openSetLog('prancha-plank','Prancha (Plank)'); addSet()")
        cols = await pg.evaluate("document.querySelector('#modal-inner .set-row').innerText")
        confere('prancha: só tempo', 'TEMPO' in cols and 'CARGA' not in cols, cols)
        await pg.evaluate("closeSetLog(false); stopRestTimer()")
        print('4. Ficha: créditos no fim, depois das informações técnicas')
        await pg.evaluate("""videoLinks['supino-reto-com-barra']='https://youtu.be/AAAAAAAAAAA'; videoCreditos['supino-reto-com-barra']={nome:'João Silva', ficha:{instagram:'joaosilva'}, biblioteca:null}; closeModal(); openExerciseSheet('Supino Reto com Barra')""")
        await pg.wait_for_timeout(400)
        ordem = await pg.evaluate("[...document.querySelectorAll('#modal-inner .ex-scroll > *')].map(e=>e.className + '|' + (e.querySelector('h4')||{}).textContent)")
        idx = lambda t: next((i for i, x in enumerate(ordem) if t in x), -1)
        confere('ordem: músculos → execução → dicas → erro comum → créditos', -1 < idx('Músculos') < idx('Como executar') < idx('Dicas') < idx('Erro comum') < idx('vc-cred'), ordem)
        confere('título "Conteúdo demonstrativo" e só o liberado', await pg.evaluate("(()=>{ const t = document.querySelector('.vc-cred').innerText; return /Conte[uú]do demonstrativo/i.test(t) && /@joaosilva/.test(t) && !/Contato/.test(t); })()"))
        print('5. Seleção de texto')
        sel = await pg.evaluate("""[getComputedStyle(document.querySelector('#modal-inner .btn')).userSelect, getComputedStyle(document.querySelector('.ex-sec p, .ex-sec li')).userSelect, getComputedStyle(document.querySelector('.vc-cred')).userSelect]""")
        confere('botão não seleciona; texto da ficha e créditos selecionam', sel[0] == 'none' and sel[1] in ('text','auto') and sel[2] in ('text','auto'), sel)
        await pg.evaluate("closeModal(); goTab('home')")
        tab = await pg.evaluate("[getComputedStyle(document.querySelector('.tab')).userSelect, getComputedStyle(document.querySelector('.tab')).webkitTouchCallout || '']")
        confere('abas não selecionam', tab[0] == 'none', tab)
        await pg.evaluate("openModal('edit-profile')")
        inp = await pg.evaluate("getComputedStyle(document.getElementById('ep-nick')).userSelect")
        confere('campos de digitação continuam selecionáveis', inp in ('text','auto'), inp)
        await pg.evaluate("closeModal()")
        print('6. Semana com menos tempo (tela)')
        await pg.evaluate("state.active='run'; runSync(true); openRunSemana()")
        await pg.evaluate("document.querySelectorAll('#rs-dias .opt-multi').forEach(o=>o.classList.remove('on')); const d=[...document.querySelectorAll('#rs-dias .opt-multi:not(.opt-off)')]; d.slice(-1).forEach(o=>o.classList.add('on')); runSemanaPrevia()")
        txt = await pg.evaluate("document.getElementById('modal-inner').innerText")
        confere('mostra Antes, Depois e o que muda antes de aplicar', 'antes' in txt.lower() and 'depois' in txt.lower() and 'não' in txt and 'volta ao plano normal' in txt, txt[:300])
        antes = await pg.evaluate("state.modules.run.plan.workouts.map(w=>w.dayIdx).join()")
        await pg.evaluate("runSemanaAplicar()"); await pg.wait_for_timeout(300)
        depois = await pg.evaluate("state.modules.run.plan.workouts.map(w=>w.dayIdx).join()")
        confere('Aplicar remonta a semana na hora', antes != depois or antes == '', (antes, depois))
        await pg.evaluate("openRunSemana(); runSemanaNormal()")
        confere('Voltar ao normal restaura os dias', await pg.evaluate("state.modules.run.plan.workouts.map(w=>w.dayIdx).join()") == antes)
        confere('sem erros de página', not erros, erros[:3])
        await b.close()
    print(f'\n{ok} verificações aprovadas, {len(falhas)} reprovadas.'); sys.exit(1 if falhas else 0)
asyncio.run(main())

async def arrasta(cdp, pg, x, y, dx, passos=14, ms=16):
    """Toque de verdade (touchStart/touchMove/touchEnd pelo Chrome): o dedo anda dx pixels."""
    await cdp.send('Input.dispatchTouchEvent', {'type':'touchStart', 'touchPoints':[{'x':x, 'y':y}]})
    for i in range(1, passos+1):
        await cdp.send('Input.dispatchTouchEvent', {'type':'touchMove', 'touchPoints':[{'x':x + dx*i/passos, 'y':y}]}); await pg.wait_for_timeout(ms)
    await cdp.send('Input.dispatchTouchEvent', {'type':'touchEnd', 'touchPoints':[]})

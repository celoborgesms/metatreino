async def provas(b):
    print('11. Preparação para provas')
    ctx, pg, erros = await nova(b)
    await pg.evaluate("mtSemente()"); await pg.wait_for_timeout(1300); await pg.evaluate("try{closeAwards()}catch(e){}; closeModal(); switchModule('run')")
    iso = "(n=>{ const d=new Date(); d.setDate(d.getDate()+n); return d.getFullYear()+'-'+String(d.getMonth()+1).padStart(2,'0')+'-'+String(d.getDate()).padStart(2,'0'); })"
    async def nudge(goal, dias):
        return await pg.evaluate(f"(()=>{{ state.evolucao={{}}; state.provaAvisos={{}}; const st=state.modules.run.setup; st.goal='{goal}'; st.raceDate={iso}({dias}); const n=maNudge()||{{}}; return {{ t:n.text||'', c:(n.dica||{{}}).completa||'' }}; }})()")

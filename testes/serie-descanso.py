#!/usr/bin/env python3
"""Beta 36: registro de séries — adicionar, editar e concluir são ações diferentes; o descanso só começa
depois de uma série concluída; a última série prevista não abre descanso; preferência de descanso automático.
Uso: python3 testes/serie-descanso.py http://localhost:8765/index.html"""
import asyncio, sys
from playwright.async_api import async_playwright
URL = sys.argv[1] if len(sys.argv) > 1 else 'http://localhost:8765/index.html'
ok = falhou = 0
def confere(nome, cond, info=''):
    global ok, falhou
    if cond: ok += 1; print('  ✅', nome)
    else: falhou += 1; print('  ❌', nome, info)
async def main():
    async with async_playwright() as p:
        b = await p.chromium.launch(executable_path='/usr/bin/google-chrome', args=['--no-sandbox'])
        pg = await b.new_page(viewport={'width':390,'height':844}, device_scale_factor=2); erros = []
        pg.on('pageerror', lambda e: erros.append(str(e)))
        await pg.goto(URL); await pg.wait_for_function("document.querySelector('.screen.active') && document.querySelector('.screen.active').id==='scr-quiz'", timeout=15000)
        await pg.evaluate("mtSemente()"); await pg.wait_for_timeout(1500); await pg.evaluate("try{closeAwards()}catch(e){}; try{closeModal()}catch(e){}; localStorage.removeItem('mt_descanso_auto')")
        await pg.evaluate("goTab('sessions')"); await pg.wait_for_timeout(400)
        ex = await pg.evaluate("(()=>{ const w = currentSelectedWorkout(state.modules.lift); const e = w.exercises.find(x=>exTipoRegistro(x.id)==='carga') || w.exercises[0]; return [e.id, e.name, parseInt(e.sets)]; })()")
        exId, nome, plan = ex
        hist_antes = await pg.evaluate(f"JSON.stringify((state.progress['{exId}']||[]).filter(p=>new Date(p.date).toDateString()!==new Date().toDateString()))")
        await pg.evaluate(f"stopRestTimer(); state.progress['{exId}'] = (state.progress['{exId}']||[]).filter(p=>new Date(p.date).toDateString()!==new Date().toDateString()); openSetLog('{exId}', {repr(nome)})")
        print('1. Abrir o exercício')
        confere('abrir não inicia descanso', await pg.evaluate("!restTimerInt"))
        confere('sem série concluída não há botão de descanso', await pg.evaluate("![...document.querySelectorAll('#modal-inner .btn')].some(b=>/descanso/i.test(b.textContent))"))
        print('2. Adicionar a 1ª série')
        await pg.evaluate("addSet()")
        confere('adicionar a 1ª série não inicia descanso', await pg.evaluate("!restTimerInt"))
        confere('a 1ª série começa pendente', await pg.evaluate("!document.querySelector('.set-row.feita') && document.querySelectorAll('#modal-inner .set-row .set-ok').length===1"))
        print('3. Concluir a 1ª série (descanso automático ligado, padrão)')
        await pg.evaluate("updateSet(0,'peso','40'); updateSet(0,'reps','10')")
        confere('editar a série não inicia descanso', await pg.evaluate("!restTimerInt"))
        await pg.evaluate("document.querySelector('#modal-inner .set-row .set-ok').click()")
        confere('concluir: a série fica marcada como feita', await pg.evaluate("document.querySelectorAll('.set-row.feita').length===1"))
        confere('concluir: o descanso começa', await pg.evaluate("!!restTimerInt"))
        fim1 = await pg.evaluate("restFimEm")
        await pg.evaluate("updateSet(0,'reps','12')"); await pg.wait_for_timeout(200)
        confere('editar uma série concluída não reinicia o descanso', await pg.evaluate(f"restFimEm === {fim1}"))
        print('4. Descanso manual (preferência desligada)')
        await pg.evaluate("stopRestTimer(); document.querySelector('.sl-auto input').click()")
        confere('preferência gravada no aparelho', await pg.evaluate("localStorage.getItem('mt_descanso_auto')==='0'"))
        await pg.evaluate("addSet()")
        confere('adicionar a 2ª série (1ª já concluída) não inicia descanso', await pg.evaluate("!restTimerInt"))
        await pg.evaluate("concluirSerie(1)")
        confere('com o automático desligado, concluir não inicia descanso', await pg.evaluate("!restTimerInt"))
        bt = await pg.evaluate("(()=>{ const b=[...document.querySelectorAll('#modal-inner .btn')].find(b=>/Iniciar descanso/.test(b.textContent)); return b ? b.className : null; })()")
        confere('aparece "Iniciar descanso" em destaque', bt and 'btn-primary' in bt, bt)
        await pg.evaluate("[...document.querySelectorAll('#modal-inner .btn')].find(b=>/Iniciar descanso/.test(b.textContent)).click()")
        confere('"Iniciar descanso" inicia o descanso', await pg.evaluate("!!restTimerInt"))
        confere('o botão vira "Reiniciar descanso"', await pg.evaluate("[...document.querySelectorAll('#modal-inner .btn')].some(b=>/Reiniciar descanso/.test(b.textContent))"))
        await pg.screenshot(path='/home/claude/teste/cap/serie-manual.png')
        print('5. Desfazer a conclusão')
        await pg.evaluate("concluirSerie(1)")
        confere('tocar de novo desfaz a marca', await pg.evaluate("document.querySelectorAll('.set-row.feita').length===1"))
        await pg.evaluate("concluirSerie(1)")
        print('6. "+ Nova série" com a anterior pendente (hábito antigo)')
        await pg.evaluate("stopRestTimer(); document.querySelector('.sl-auto input').click(); addSet()")   # automático de volta; 3ª série pendente
        await pg.evaluate("stopRestTimer(); addSet()")   # adicionou a 4ª com a 3ª pendente
        confere('a série pendente anterior é concluída e o descanso começa', await pg.evaluate("curLog.feitas[2]===true && !!restTimerInt"))
        print(f'7. Última série prevista ({plan} séries no plano)')
        await pg.evaluate("stopRestTimer(); while(curLog.entry.sets.length > %d) delSet(curLog.entry.sets.length-1); while(curLog.entry.sets.length < %d) addSet(); stopRestTimer();" % (plan, plan))
        await pg.evaluate("curLog.feitas = curLog.feitas.map((v,i)=>i < curLog.entry.sets.length-1); renderSetLogModal(); stopRestTimer();")
        await pg.evaluate(f"concluirSerie({plan-1})")
        confere('concluir a última série prevista não inicia descanso', await pg.evaluate("!restTimerInt"))
        confere('mostra o aviso de fim do exercício', await pg.evaluate("!!document.querySelector('#modal-inner .sl-fim')"))
        await pg.screenshot(path='/home/claude/teste/cap/serie-fim.png')
        print('8. Salvar e reabrir')
        valores = await pg.evaluate("JSON.stringify(curLog.entry.sets)")
        await pg.evaluate("closeSetLog(true)")
        hoje = await pg.evaluate(f"JSON.stringify((state.progress['{exId}']||[]).find(p=>new Date(p.date).toDateString()===new Date().toDateString()).sets)")
        confere('cargas e repetições salvas como registradas', hoje == valores, (hoje, valores))
        confere('nada novo gravado nas séries (sem campo extra)', '"feita"' not in hoje and '"ok"' not in hoje)
        hist_depois = await pg.evaluate(f"JSON.stringify((state.progress['{exId}']||[]).filter(p=>new Date(p.date).toDateString()!==new Date().toDateString()))")
        confere('histórico de dias anteriores intacto', hist_antes == hist_depois)
        await pg.evaluate(f"openSetLog('{exId}', {repr(nome)})")
        confere('ao reabrir, as séries salvas aparecem concluídas', await pg.evaluate("document.querySelectorAll('.set-row.feita').length === curLog.entry.sets.length"))
        await pg.evaluate("closeSetLog(false)")
        print('9. Tela de 360 px')
        await pg.set_viewport_size({'width':360,'height':740}); await pg.evaluate(f"openSetLog('{exId}', {repr(nome)})"); await pg.wait_for_timeout(300)
        larg = await pg.evaluate("Math.max(...[...document.querySelectorAll('#modal-inner .set-row')].map(r=>r.scrollWidth - r.clientWidth))")
        confere('linha da série cabe em 360 px', larg <= 0, larg)
        await pg.screenshot(path='/home/claude/teste/cap/serie-360.png')
        confere('sem erros de página', not erros, erros[:3])
        await b.close()
    print(f'\n{ok} verificações aprovadas, {falhou} reprovadas.')
    sys.exit(1 if falhou else 0)
asyncio.run(main())
